-- C05 (#90) : referentiels transverses du catalogue.
-- Les produits (C01 #3) les referencent par des migrations suivantes (V2, ...).
-- Tables et colonnes en francais, comme dans les autres services et le modele
-- de donnees ; le Java reste en anglais.
-- SQL commun a PostgreSQL et a H2 en mode PostgreSQL : pas de syntaxe propre a
-- l'un des deux.

CREATE TABLE marque (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nom           VARCHAR(100)  NOT NULL,
    slug          VARCHAR(120)  NOT NULL,
    description   VARCHAR(2000),
    logo_url      VARCHAR(500),
    date_creation TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    date_maj      TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_marque_nom UNIQUE (nom),
    CONSTRAINT uk_marque_slug UNIQUE (slug)
);

CREATE TABLE univers (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nom           VARCHAR(100)  NOT NULL,
    slug          VARCHAR(120)  NOT NULL,
    description   VARCHAR(2000),
    image_url     VARCHAR(500),
    position      INTEGER       NOT NULL DEFAULT 0,
    date_creation TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    date_maj      TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_univers_nom UNIQUE (nom),
    CONSTRAINT uk_univers_slug UNIQUE (slug)
);

-- Arborescence : une categorie racine n'a pas de parent. Deux categories de
-- branches differentes peuvent porter le meme nom (« Accessoires »), pas le
-- meme slug, qui sert d'URL.
CREATE TABLE categorie (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nom           VARCHAR(100)  NOT NULL,
    slug          VARCHAR(120)  NOT NULL,
    description   VARCHAR(2000),
    parent_id     BIGINT,
    position      INTEGER       NOT NULL DEFAULT 0,
    date_creation TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    date_maj      TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_categorie_slug UNIQUE (slug),
    CONSTRAINT fk_categorie_parent FOREIGN KEY (parent_id) REFERENCES categorie (id)
);

CREATE INDEX idx_categorie_parent ON categorie (parent_id);

-- Taux en pourcentage : 20.00 pour 20 %. Un seul taux par defaut, garanti par
-- le service, qui verrouille la table pour chaque ecriture (un index partiel ne
-- passerait pas sur H2).
CREATE TABLE tva (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    libelle       VARCHAR(50)   NOT NULL,
    taux          NUMERIC(5, 2) NOT NULL,
    par_defaut    BOOLEAN       NOT NULL DEFAULT FALSE,
    date_creation TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    date_maj      TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_tva_libelle UNIQUE (libelle),
    CONSTRAINT ck_tva_taux CHECK (taux >= 0 AND taux <= 100)
);

