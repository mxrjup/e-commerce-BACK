-- C05 (#90) : referentiels transverses du catalogue.
-- Les produits (C01 #3) les referencent par des migrations suivantes (V2, ...).
-- SQL commun a PostgreSQL et a H2 en mode PostgreSQL : pas de syntaxe propre a
-- l'un des deux.

CREATE TABLE brand (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(100)  NOT NULL,
    slug        VARCHAR(120)  NOT NULL,
    description VARCHAR(2000),
    logo_url    VARCHAR(500),
    created_at  TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at  TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_brand_name UNIQUE (name),
    CONSTRAINT uk_brand_slug UNIQUE (slug)
);

CREATE TABLE universe (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(100)  NOT NULL,
    slug        VARCHAR(120)  NOT NULL,
    description VARCHAR(2000),
    image_url   VARCHAR(500),
    position    INTEGER       NOT NULL DEFAULT 0,
    created_at  TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at  TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_universe_name UNIQUE (name),
    CONSTRAINT uk_universe_slug UNIQUE (slug)
);

-- Arborescence : une categorie racine n'a pas de parent. Deux categories de
-- branches differentes peuvent porter le meme nom (« Accessoires »), pas le
-- meme slug, qui sert d'URL.
CREATE TABLE category (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(100)  NOT NULL,
    slug        VARCHAR(120)  NOT NULL,
    description VARCHAR(2000),
    parent_id   BIGINT,
    position    INTEGER       NOT NULL DEFAULT 0,
    created_at  TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at  TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_category_slug UNIQUE (slug),
    CONSTRAINT fk_category_parent FOREIGN KEY (parent_id) REFERENCES category (id)
);

CREATE INDEX idx_category_parent ON category (parent_id);

-- Taux en pourcentage : 20.00 pour 20 %. Un seul taux par defaut, garanti par
-- le service (un index partiel ne passerait pas sur H2).
CREATE TABLE vat_rate (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    label       VARCHAR(50)   NOT NULL,
    rate        NUMERIC(5, 2) NOT NULL,
    is_default  BOOLEAN       NOT NULL DEFAULT FALSE,
    created_at  TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at  TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_vat_rate_label UNIQUE (label),
    CONSTRAINT ck_vat_rate_range CHECK (rate >= 0 AND rate <= 100)
);

