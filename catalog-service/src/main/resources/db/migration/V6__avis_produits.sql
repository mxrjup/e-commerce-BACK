CREATE TABLE avis_produit (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    produit_id     BIGINT NOT NULL REFERENCES produit (id) ON DELETE CASCADE,
    auteur_subject VARCHAR(255) NOT NULL,
    note           INTEGER NOT NULL CHECK (note BETWEEN 1 AND 5),
    commentaire    VARCHAR(2000) NOT NULL CHECK (CHAR_LENGTH(TRIM(commentaire)) > 0),
    date_creation  TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    date_maj       TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_avis_produit_auteur UNIQUE (produit_id, auteur_subject)
);

CREATE INDEX idx_avis_produit_page ON avis_produit (produit_id, date_creation DESC, id DESC);
