-- C01 (#3) : produits, variantes, attributs, specifications, images, stock.
-- Le produit est la fiche generique ; la variante est l'unite reellement
-- vendue (SKU, prix, poids, stock) : c'est elle que le panier et la commande
-- referencent. Les declinaisons (couleur, layout...) passent par
-- attribut / valeur_attribut / variante_valeur.
-- Les cles etrangeres vers marque, categorie, univers et tva sont de vraies
-- contraintes : tout est dans la base du catalogue.
-- SQL commun a PostgreSQL et a H2 en mode PostgreSQL.

-- Un taux inactif n'est plus propose pour un nouveau produit, mais reste
-- valable pour les produits qui l'utilisent deja.
ALTER TABLE tva ADD COLUMN actif BOOLEAN NOT NULL DEFAULT TRUE;

CREATE TABLE produit (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titre         VARCHAR(150)   NOT NULL,
    slug          VARCHAR(120)   NOT NULL,
    -- HTML issu de l'editeur WYSIWYG du back-office (C16).
    description   VARCHAR(20000),
    statut        VARCHAR(20)    NOT NULL DEFAULT 'BROUILLON',
    marque_id     BIGINT         NOT NULL,
    categorie_id  BIGINT         NOT NULL,
    tva_id        BIGINT         NOT NULL,
    date_creation TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    date_maj      TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_produit_slug UNIQUE (slug),
    CONSTRAINT ck_produit_statut CHECK (statut IN ('BROUILLON', 'PUBLIE', 'ARCHIVE')),
    CONSTRAINT fk_produit_marque FOREIGN KEY (marque_id) REFERENCES marque (id),
    CONSTRAINT fk_produit_categorie FOREIGN KEY (categorie_id) REFERENCES categorie (id),
    CONSTRAINT fk_produit_tva FOREIGN KEY (tva_id) REFERENCES tva (id)
);

CREATE INDEX idx_produit_marque ON produit (marque_id);
CREATE INDEX idx_produit_categorie ON produit (categorie_id);
CREATE INDEX idx_produit_statut ON produit (statut);

-- Prix hors taxes ; la TVA vient du produit. Le stock ne peut pas passer sous
-- zero : la base refuse la survente meme si deux commandes arrivent ensemble.
CREATE TABLE variante (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    produit_id     BIGINT         NOT NULL,
    sku            VARCHAR(64)    NOT NULL,
    -- Prix grossiste : back-office et marge seulement, jamais expose en vitrine.
    prix_achat_ht  NUMERIC(10, 2) NOT NULL,
    prix_vente_ht  NUMERIC(10, 2) NOT NULL,
    -- NULL quand la variante n'est pas en promotion.
    prix_remise_ht NUMERIC(10, 2),
    -- Taxe fixe DEEE ajoutee au prix ; NULL si la variante n'y est pas soumise.
    ecotaxe        NUMERIC(10, 2),
    -- En kilogrammes, pour les frais de port.
    poids          NUMERIC(8, 3)  NOT NULL,
    stock          INTEGER        NOT NULL DEFAULT 0,
    seuil_alerte   INTEGER        NOT NULL DEFAULT 0,
    date_creation  TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    date_maj       TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_variante_sku UNIQUE (sku),
    CONSTRAINT ck_variante_prix CHECK (prix_achat_ht >= 0 AND prix_vente_ht >= 0),
    CONSTRAINT ck_variante_remise CHECK (prix_remise_ht IS NULL
        OR (prix_remise_ht >= 0 AND prix_remise_ht < prix_vente_ht)),
    CONSTRAINT ck_variante_ecotaxe CHECK (ecotaxe IS NULL OR ecotaxe >= 0),
    CONSTRAINT ck_variante_poids CHECK (poids >= 0),
    CONSTRAINT ck_variante_stock CHECK (stock >= 0 AND seuil_alerte >= 0),
    CONSTRAINT fk_variante_produit FOREIGN KEY (produit_id) REFERENCES produit (id) ON DELETE CASCADE
);

CREATE INDEX idx_variante_produit ON variante (produit_id);

-- Ce qui fait varier un produit : Couleur, Layout clavier, Capacite...
CREATE TABLE attribut (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nom           VARCHAR(50)  NOT NULL,
    date_creation TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    date_maj      TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_attribut_nom UNIQUE (nom)
);

CREATE TABLE valeur_attribut (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    attribut_id BIGINT      NOT NULL,
    valeur      VARCHAR(50) NOT NULL,
    position    INTEGER     NOT NULL DEFAULT 0,
    CONSTRAINT uk_valeur_attribut UNIQUE (attribut_id, valeur),
    CONSTRAINT fk_valeur_attribut FOREIGN KEY (attribut_id) REFERENCES attribut (id) ON DELETE CASCADE
);

-- Une variante a au plus une valeur par attribut : regle portee par le
-- service (C04), une contrainte demanderait de dupliquer attribut_id ici.
CREATE TABLE variante_valeur (
    variante_id BIGINT NOT NULL,
    valeur_id   BIGINT NOT NULL,
    PRIMARY KEY (variante_id, valeur_id),
    CONSTRAINT fk_variante_valeur_variante FOREIGN KEY (variante_id) REFERENCES variante (id) ON DELETE CASCADE,
    CONSTRAINT fk_variante_valeur_valeur FOREIGN KEY (valeur_id) REFERENCES valeur_attribut (id)
);

CREATE INDEX idx_variante_valeur_valeur ON variante_valeur (valeur_id);

-- Les photos d'une variante (le noir et le blanc n'ont pas les memes).
-- position 1 = miniature principale. Pas d'unicite sur la position : le
-- reordonnancement (C06) reecrit toutes les positions d'un coup.
CREATE TABLE variante_image (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    variante_id BIGINT       NOT NULL,
    url         VARCHAR(500) NOT NULL,
    position    INTEGER      NOT NULL DEFAULT 1,
    CONSTRAINT fk_variante_image_variante FOREIGN KEY (variante_id) REFERENCES variante (id) ON DELETE CASCADE
);

CREATE INDEX idx_variante_image_variante ON variante_image (variante_id);

-- Caracteristiques descriptives, communes a toutes les variantes du produit.
CREATE TABLE produit_specification (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    produit_id BIGINT       NOT NULL,
    cle        VARCHAR(100) NOT NULL,
    valeur     VARCHAR(500) NOT NULL,
    position   INTEGER      NOT NULL DEFAULT 0,
    CONSTRAINT uk_produit_specification UNIQUE (produit_id, cle),
    CONSTRAINT fk_produit_specification_produit FOREIGN KEY (produit_id) REFERENCES produit (id) ON DELETE CASCADE
);

CREATE TABLE produit_univers (
    produit_id BIGINT NOT NULL,
    univers_id BIGINT NOT NULL,
    PRIMARY KEY (produit_id, univers_id),
    CONSTRAINT fk_produit_univers_produit FOREIGN KEY (produit_id) REFERENCES produit (id) ON DELETE CASCADE,
    CONSTRAINT fk_produit_univers_univers FOREIGN KEY (univers_id) REFERENCES univers (id)
);

CREATE INDEX idx_produit_univers_univers ON produit_univers (univers_id);
