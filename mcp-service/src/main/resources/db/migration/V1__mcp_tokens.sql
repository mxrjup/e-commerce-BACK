-- M03 (#92) : jetons d'acces des clients MCP (Claude Desktop, MCP Inspector).
-- Le jeton lui-meme n'est jamais stocke : seulement son empreinte SHA-256, et
-- son debut (prefixe) pour que le back-office le reconnaisse.
-- Un jeton revoque n'est pas supprime : il reste pour l'historique.
-- SQL commun a PostgreSQL et a H2 en mode PostgreSQL.

CREATE TABLE jeton_mcp (
    id                        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nom                       VARCHAR(100) NOT NULL,
    prefixe                   VARCHAR(16)  NOT NULL,
    empreinte                 CHAR(64)     NOT NULL,
    -- Portees separees par des espaces, comme le « scope » OAuth.
    portees                   VARCHAR(500) NOT NULL,
    -- Identifiant Keycloak (sub) de l'admin qui a cree, ou revoque, le jeton.
    cree_par                  VARCHAR(64),
    revoque_par               VARCHAR(64),
    date_creation             TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    date_expiration           TIMESTAMP(6) WITH TIME ZONE,
    date_revocation           TIMESTAMP(6) WITH TIME ZONE,
    date_derniere_utilisation TIMESTAMP(6) WITH TIME ZONE,
    CONSTRAINT uk_jeton_mcp_empreinte UNIQUE (empreinte)
);
